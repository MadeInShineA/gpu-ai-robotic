namespace PI::sequentiel
    {
    double loop(int n)
        {
            const double dx = 1 / (double) n;

            double sum = 0;
            double xi;

            for (int i = 0; i < n; i++){
                xi = i * dx;
                sum += f(xi);
            }

        return sum * dx;
        }

    } // namespace PI::sequentiel

